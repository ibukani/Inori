"""Generate both wire bindings from the canonical schema. Unsupported forms fail closed.

Only the deliberately small schema subset used by v1 is supported. This is not a
general-purpose JSON Schema validator. CI checks generated files for drift.
"""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT / "contracts/v1.json").read_text(encoding="utf-8"))

def ident(value):
    return "".join(word[:1].upper() + word[1:] for word in re.split(r"[^a-zA-Z0-9]+", value))

def typename(node, language):
    if "$ref" in node:
        return node["$ref"].split("/")[-1]
    if "anyOf" in node:
        non_null = [n for n in node["anyOf"] if n.get("type") != "null"]
        if len(non_null) != 1 or len(node["anyOf"]) != 2:
            raise ValueError("only nullable anyOf is supported")
        inner = typename(non_null[0], language)
        return f"Option<{inner}>" if language == "rust" else f"{inner} | null"
    kind = node.get("type")
    if kind == "array":
        inner = typename(node["items"], language)
        return f"Vec<{inner}>" if language == "rust" else f"Array<{inner}>"
    if kind == "object":
        if isinstance(node.get("additionalProperties"), dict):
            inner = typename(node["additionalProperties"], language)
            return f"std::collections::BTreeMap<String, {inner}>" if language == "rust" else f"Record<string, {inner}>"
        if "properties" in node:
            raise ValueError("nested structured objects require a named definition")
    if "enum" in node:
        return "String" if language == "rust" else " | ".join(json.dumps(v) for v in node["enum"])
    values = {"string": ("String", "string"), "integer": ("u64" if node.get("minimum") == 0 else "i64", "number"), "number": ("f64", "number"), "boolean": ("bool", "boolean"), "object": ("serde_json::Value", "unknown"), None: ("serde_json::Value", "unknown")}
    if kind not in values:
        raise ValueError(f"unsupported schema type: {kind}")
    return values[kind][0 if language == "rust" else 1]

def generate():
    rust = ["// Generated by tools/generate_contracts.py; do not edit.", "use serde::{Deserialize, Serialize};", "pub const PROTOCOL_VERSION: &str = \\\"1.0\\\";".replace("\\\"", '"'), "pub const PROTOCOL_MAJOR: u64 = 1;"]
    typescript = ["// Generated by tools/generate_contracts.py; do not edit.", 'export const PROTOCOL_VERSION = "1.0" as const;']
    for name, node in SCHEMA["$defs"].items():
        if "enum" in node:
            rust += ["#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]", f"pub enum {name} {{"]
            for value in node["enum"]:
                rust += [f"    #[serde(rename = {json.dumps(value)})]", f"    {ident(value)},"]
            rust += ["}"]
            typescript += [f"export type {name} = " + " | ".join(json.dumps(v) for v in node["enum"]) + ";"]
        else:
            if node.get("type") != "object" or set(node["required"]) != set(node["properties"]):
                raise ValueError("v1 objects require explicit fields; use nullable fields for optional values")
            secret_fields = {field for field, value in node["properties"].items() if value.get("writeOnly")}
            rust += ["#[derive(Clone, Serialize, Deserialize)]" if secret_fields else "#[derive(Debug, Clone, Serialize, Deserialize)]", "#[serde(deny_unknown_fields)]", f"pub struct {name} {{"]
            typescript += [f"export interface {name} {{"]
            for field, value in node["properties"].items():
                rust += [f"    pub {field}: {typename(value, 'rust')},"]
                typescript += [f"  {field}: {typename(value, 'ts')};"]
            rust += ["}"]
            if secret_fields:
                rust += [f"impl std::fmt::Debug for {name} {{", "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {", f'        f.debug_struct("{name}")']
                for field in node["properties"]:
                    value = '&"<redacted>"' if field in secret_fields else f'&self.{field}'
                    rust += [f'            .field("{field}", {value})']
                rust += ["            .finish()", "    }", "}"]
            typescript += ["}"]
    return {ROOT / "crates/protocol/src/generated.rs": "\\n".join(rust).replace('\\n', '\n') + "\n", ROOT / "packages/sdk-typescript/src/generated.ts": "\\n".join(typescript).replace('\\n', '\n') + "\n"}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"outdated generated contract: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

if __name__ == "__main__":
    main()
